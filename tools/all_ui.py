"""The four machine-page splashes, in one unified UI layer.

Feral, BLAST, PUNCH and LiXR each get a picture index of their own (6, 7, 8, 9). The
OS's MACHINES page, the track page and the small track strip are redirected for those
indices to Bitmap objects built here; stock pictures (0..5) keep the OS's path.
"""
import pathlib
import struct
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import blast_screens
import punch_screens
import feral_screens
import lixr_screens

ENGINES = (
    ("Feral", 6, feral_screens),
    ("BLAST", 7, blast_screens),
    ("PUNCH", 8, punch_screens),
    ("LiXR", 9, lixr_screens),
)

# The four absolute offsets, in bytes, of image x 28 in the OS's stock arrays.
OFFSETS = tuple((name, index * 28) for name, index, _ in ENGINES)


def _bm(name, art, w, h, module):
    return module.bitmap(art, w, h), module.mask(w, h)


def icons_header():
    out = ["/* The four machine-page pictures, generated by tools/gen_all.py. */",
           "#ifndef ALL_ICONS_H", "#define ALL_ICONS_H", ""]
    for ename, _, module in ENGINES:
        for suffix, art, w, h in module.SPRITES:
            bm = feral_screens.bitmap(art, w, h) if module is lixr_screens else module.bitmap(art, w, h)
            mk = feral_screens.mask(w, h) if module is lixr_screens else module.mask(w, h)
            for kind, words in (("IMG", bm), ("MSK", mk)):
                out.append(f"static const unsigned int UI_{kind}_{ename.upper()}_{suffix.upper()}[{len(words)}] = {{")
                for i in range(0, len(words), 6):
                    out.append("\t" + ", ".join(f"{x:#010x}" for x in words[i:i + 6]) + ",")
                out.append("};")
            out.append("")
    return "\n".join(out + ["#endif", ""])


def ui_source():
    out = ["/* Bitmap objects of the four splashes (OS Bitmap constructor 0x40070172). */",
           "#include \"all_icons.h\"", "",
           "typedef unsigned int u32;",
           "struct bitmap { u32 vt, w, h, wpc, img, mask, flag; };",
           "#define BITMAP_VT 0x401117c8u",
           "#define BITMAP(name, w, h, img, mask) const struct bitmap name = { BITMAP_VT, w, h, ((h) + 31) >> 5, (u32)(img), (u32)(mask), 0 }",
           ""]
    for ename, _, module in ENGINES:
        for suffix, art, w, h in module.SPRITES:
            e = ename.upper()
            out.append(f"BITMAP(ui_bm_{ename.lower()}_{suffix}, {w}, {h}, UI_IMG_{e}_{suffix.upper()}, UI_MSK_{e}_{suffix.upper()});")
    return "\n".join(out + [""])


def compile_ui(tmp, pay):
    import gen_sdvintage_exact as gx
    (tmp / "all_icons.h").write_text(icons_header())
    (tmp / "all_ui.c").write_text(ui_source())
    o, elf, b = tmp / "all_ui.o", tmp / "all_ui.elf", tmp / "all_ui.bin"
    gx.run([gx.CROSS + "gcc", "-mcpu=54418", "-O2", "-ffreestanding", "-fno-builtin", "-fno-pic",
            "-fno-common", "-fno-tree-loop-distribute-patterns", "-nostdlib", "-fomit-frame-pointer",
            "-Wall", "-Wextra", "-Werror", "-I" + str(tmp), "-c", str(tmp / "all_ui.c"), "-o", str(o)])
    gx.run([gx.CROSS + "ld", "-Ttext", f"{pay:#x}", "-o", str(elf), str(o)])
    gx.run([gx.CROSS + "objcopy", "-O", "binary", str(elf), str(b)])
    syms = {q[2]: int(q[0], 16) for q in (l.split() for l in gx.run([gx.CROSS + "nm", str(elf)]).splitlines())
            if len(q) == 3}
    return b.read_bytes(), syms


def _setv(name, syms, key):
    return f"\t.set {name}, {syms[key]:#x}"


def patch_detours(text, syms):
    """Standard detours -> four-picture detours. syms are the ui_bm_* addresses."""
    head = []
    for ename, _, _ in ENGINES:
        for s in ("a", "b", "c"):
            head.append(_setv(f"UI_BM_{ename.upper()}_{s.upper()}", syms, f"ui_bm_{ename.lower()}_{s}"))
    head = "\n".join(head) + "\n"

    def card_dispatch(reg, table):
        out = []
        for ename, off in OFFSETS:
            out += [f"\tcmpi.l #{off}, {reg}", f"\tbeq.s card_{ename.lower()}", ]
        out += [f"\tmovea.l {table:#x}, %a1", f"\tadda.l {reg}, %a1", "\tbra.w card_draw"]
        for ename, off in OFFSETS:
            out += [f"card_{ename.lower()}:", f"\tlea UI_BM_{ename.upper()}_A, %a1", "\tbra.w card_draw"]
        out += ["card_draw:"]
        return "\n".join(out) + "\n"

    def emblem_dispatch(reg):
        out = []
        for ename, off in OFFSETS:
            out += [f"\tcmpi.l #{off}, {reg}", f"\tbeq.s emb_{ename.lower()}", ]
        out += [f"\tadd.l 0x40fe384c, {reg}", "\tbra.w emb_draw"]
        for ename, off in OFFSETS:
            out += [f"emb_{ename.lower()}:", f"\tmove.l #UI_BM_{ename.upper()}_B, {reg}", "\tbra.w emb_draw"]
        out += ["emb_draw:"]
        return "\n".join(out) + "\n"

    drum = """\t.globl\tdrum_icons
drum_icons:
\tmove.l %d3, %d0
\tbsr.w shown
\tmove.l %d0, %d4
\tlsl.l #2, %d0
\tlsl.l #5, %d4
\tsub.l %d0, %d4
\tpea 0x1
\tpea 0x17
\tpea 0x20
\tlea 0x40071da4, %a2
""" + card_dispatch("%d4", 0x40fe32cc) + """\tmove.l %a1, -(%sp)
\tmove.l %d2, -(%sp)
\tjsr (%a2)
\tlea 48(%sp), %sp
\tpea 0x1
\tpea 0x22
""" + emblem_dispatch("%d4") + """\tpea 0x60
\tmove.l %d4, -(%sp)
\tmove.l %d2, -(%sp)
\tjsr (%a2)
\tlea 20(%sp), %sp
\tjmp 0x400a2680
"""
    small = """\t.globl\tsmall_icon
small_icon:
\tlea 10(%a0), %a0
\tmove.l %a0, -(%sp)
\tmove.l 16(%fp), -(%sp)
\tmove.l %d2, %d0
\tbpl.s 1f
\tmoveq #0, %d0
1:
\tmoveq #9, %d1
\tcmp.l %d0, %d1
\tbge.s 3f
\tbsr.w shown
\tmoveq #9, %d1
\tcmp.l %d0, %d1
\tbge.s 3f
\tmoveq #9, %d0
3:
\tjmp 0x400a4dde
"""
    if text.count(blast_screens.OLD_DRUM) != 1 or text.count(blast_screens.OLD_SMALL) != 1:
        raise SystemExit("!! the standard detours changed")
    text = text.replace(blast_screens.OLD_DRUM, drum).replace(blast_screens.OLD_SMALL, small)

    stubs = []
    for i, (va, arr, lab, _) in enumerate(blast_screens.SITES):
        stubs.append(f"{lab}_all{i}:")
        for ename, off in OFFSETS:
            stubs += [f"\tcmpi.l #{off}, %d0", f"\tbeq.s site{i}_{ename.lower()}"]
        stubs += [f"\tadd.l {arr:#x}, %d0", f"\tjmp {va + 6:#x}"]
        for ename, off in OFFSETS:
            stubs += [f"site{i}_{ename.lower()}:", f"\tmove.l #UI_BM_{ename.upper()}_C, %d0", f"\tjmp {va + 6:#x}"]
    return head + text + "\n" + "\n".join(stubs) + "\n"


def site_writes(img, base, ssyms):
    out = []
    for i, (va, arr, lab, _) in enumerate(blast_screens.SITES):
        old = img[va - base:va - base + 6]
        if old != bytes.fromhex("d0b9") + struct.pack(">I", arr):
            raise SystemExit(f"!! {va:#x}: not add.l {arr:#x}, d0")
        out.append({"off": va - base, "old": old.hex(),
                    "new": (bytes.fromhex("4ef9") + struct.pack(">I", ssyms[f"{lab}_all{i}"])).hex()})
    return out


def clamp_writes(writes, base):
    seen = 0
    for w in writes:
        if w and w["off"] + base in blast_screens.CLAMPS:
            if (w["old"], w["new"]) != ("7005", "7001"):
                raise SystemExit(f"!! {w['off'] + base:#x}: {w['old']} -> {w['new']}, expected 7005 -> 7001")
            w["new"] = "7009"
            seen += 1
    if seen != len(blast_screens.CLAMPS):
        raise SystemExit("!! the clamps are not in the writes")
