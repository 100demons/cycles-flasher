#!/usr/bin/env python3
"""Generates the tweak of the Feral machine alone: 64-feral9.json.

Feral is a package now (tools/machines/feral9/): nine noisy synthesis models on one added machine,
with COLOR/SWEEP/CONTOUR labels rewritten per model. Its custom SHAPE display and MACHINES-page
pictures are not ported yet; SHAPE shows the model number for now.

This generator compiles the package's sources with the manifest's recipe into feral9.o, then composes
the machine alone through tools/compose.py. It writes the result into tweaks/ so registry.py,
check_overlaps.py and build.py -t feral9 see it.

    python3 tools/gen_feral9.py --cycles model-cycles_OS1.13.syx [--check]
"""
import argparse
import json
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import compose                     # noqa: E402
import gen_macro as gm             # noqa: E402
import gen_sdvintage_exact as gx   # noqa: E402
import gen_sdvintage_7th as g7     # noqa: E402

OUT = compose.DEV / "64-feral9.json"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", required=True, help="official model-cycles_OS1.13.syx")
    ap.add_argument("--check", action="store_true", help="checks that the committed files match")
    args = ap.parse_args()
    img = g7.cycles_main(args.cycles)
    if len(img) != gx.IMAGE_LEN:
        raise SystemExit("!! not the official MAIN OS 1.13")
    m = compose.load_manifest("feral9")
    with tempfile.TemporaryDirectory() as d:
        obj = compose.build_object(m, pathlib.Path(d))
    bad = compose.emit_bytes(compose.object_path(m), obj, args.check)
    tweak, info = compose.compose(img, ["feral9"])
    tweak["description"].append("Generated by tools/gen_feral9.py through tools/compose.py.")
    text = json.dumps(tweak, indent=1, ensure_ascii=False) + "\n"
    p = info["packages"][0]
    print(f"  feral9: {len(tweak['writes'])} writes, code {p['code']} bytes, variables {p['bss']} bytes, "
          f"{info['image']} bytes added to the image, {len(tweak['conflicts'])} conflicts computed")
    if gm.emit(OUT, text, args.check) or bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
