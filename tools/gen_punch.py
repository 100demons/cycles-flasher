#!/usr/bin/env python3
"""Generates the tweak of the PUNCH machine alone: 67-punch.json.

PUNCH is a package now (tools/machines/punch/): 12 OPL2-style FM percussion models on one added machine,
COLOR showing the FM index, SHAPE the model names (KIK..ZAP) and SWEEP the ratio names (1:4..15X), stepped
one detent at a time. Its custom MACHINES-page splash is not ported yet; the picture stays TONE's.

This generator compiles the package's sources with the manifest's recipe into punch.o, then composes the
machine alone through tools/compose.py. It writes the result into tweaks/ so registry.py, check_overlaps.py
and build.py -t punch see it. It also computes punch_tables.h (the OPL2 log-sine and power tables, rebuilt
from the chip's published math, not copied from a ROM dump).

    python3 tools/gen_punch.py --cycles model-cycles_OS1.13.syx [--check]
    python3 tools/gen_punch.py            # punch_tables.h only

Built with m68k-elf-gcc 16.2 (or m68k-linux-gnu-gcc): another GCC gives other bytes, and --check says so.
"""
import argparse
import json
import math
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import compose                     # noqa: E402
import gen_macro as gm             # noqa: E402
import gen_sdvintage_exact as gx   # noqa: E402
import gen_sdvintage_7th as g7     # noqa: E402

DEV = HERE.parent / "tweaks" / "model-cycles_OS1.13"
OUT = DEV / "67-punch.json"
SRC = HERE / "machines" / "punch"
TABLES = SRC / "punch_tables.h"

FS = 48000.0
BLK = 32
DB_UNITS = 256 / (20 * math.log10(2))             # log units per dB (256 = one octave of amplitude)
LFO_CLOCK = 49716.0                               # the OPL2's sample rate (14.318 MHz / 288)


def tables():
    """(name, C type, values) of punch_tables.h, and the #defines."""
    t = []
    # TINY's tables (gen_tables.py of the TINY add-on), same formulas
    t.append(("FM_SEMI_INC", "u32", [round(2 ** 32 * 440.0 * 2 ** ((n - 69) / 12.0) / FS) for n in range(13)]))
    t.append(("FM_LOGSIN", "u16", [round(-math.log2(math.sin((2 * i + 1) * math.pi / 1024.0)) * 256)
                                   for i in range(256)]))
    t.append(("FM_POW", "u16", [round(8192 * 2 ** (-(i + 1) / 256.0)) for i in range(256)]))
    # PUNCH's OPL2 multipliers plus the percussion ratios around them. 4:1 is present and is the default step;
    # 1:4, 1:3, 2:3, 5:4, 3:2, 5:2, 7:2 and 9:2 are new.
    t.append(("FM_MULT", "u16", [round(r * 256) for r in
                                 (0.25, 1 / 3, 0.5, 2 / 3, 1, 1.25, 1.5, 2, 2.5, 3, 3.5, 4, 4.5, 5, 6, 7, 8, 9,
                                  10, 12, 15)]))
    sixty = 60 * DB_UNITS
    t.append(("FM_RATE", "u32", [round(sixty * 65536 / (0.005 * 2000 ** (k / 127) * FS)) for k in range(128)]))
    t.append(("FM_PDECAY", "u16", [round(65536 * math.exp(-BLK / (0.001 * 1000 ** (k / 127) * FS))) for k in range(128)]))
    t.append(("FM_EXP2", "u32", [round(65536 * 2 ** (i / 256)) for i in range(256)]))
    t.append(("FM_CENTS", "u16", [round(65536 * (2 ** (c / 1200) - 1)) for c in range(64)]))
    k = {
        "FM_LFO_VIB": round(2 ** 32 * (LFO_CLOCK / 8192) * BLK / FS),     # 6.07 Hz
        "FM_LFO_AM": round(2 ** 32 * (LFO_CLOCK / 13432) * BLK / FS),     # 3.70 Hz
    }
    return t, k


def tables_header():
    t, k = tables()
    out = ["/* PUNCH's tables, computed by tools/gen_punch.py: do not edit by hand. */",
           "#ifndef PUNCH_TABLES_H", "#define PUNCH_TABLES_H", ""]
    for name, v in k.items():
        out.append(f"#define {name} {v:#x}u")
    out.append("")
    for name, typ, v in t:
        out.append(f"static const {typ} {name}[{len(v)}] = {{")
        for i in range(0, len(v), 10):
            out.append("\t" + ", ".join(str(x) for x in v[i:i + 10]) + ",")
        out.append("};")
    return "\n".join(out + ["", "#endif", ""])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", help="the official model-cycles_OS1.13.syx (without it: punch_tables.h only)")
    ap.add_argument("--check", action="store_true", help="checks that the committed files match")
    args = ap.parse_args()
    bad = gm.emit(TABLES, tables_header(), args.check)
    if args.cycles:
        img = g7.cycles_main(args.cycles)
        if len(img) != gx.IMAGE_LEN:
            raise SystemExit("!! this is not the official MAIN OS 1.13")
        m = compose.load_manifest("punch")
        with tempfile.TemporaryDirectory() as d:
            obj = compose.build_object(m, pathlib.Path(d))
        bad |= compose.emit_bytes(compose.object_path(m), obj, args.check)
        tweak, info = compose.compose(img, ["punch"])
        tweak["description"].append("Generated by tools/gen_punch.py through tools/compose.py.")
        text = json.dumps(tweak, indent=1, ensure_ascii=False) + "\n"
        p = info["packages"][0]
        print(f"  punch: {len(tweak['writes'])} writes, code {p['code']} bytes, variables {p['bss']} bytes, "
              f"{info['image']} bytes added to the image, {len(tweak['conflicts'])} conflicts computed")
        bad |= gm.emit(OUT, text, args.check)
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
