#!/usr/bin/env python3
"""Generates the tweak of the LiXR machine alone: 36-lixr.json.

LiXR is a clean-room fixed-point drum voice in the spirit of the Sonic Potions LXR drum voices, with a
sample-rate decimator in place of the filter (notes 75, from the private source drop). It is a pure machine:
four knobs, update/render, no hook into the OS and no RAM claim of its own, so its package is the big brother
of tools/machines/refmachine/.

This generator compiles the package's sources with the manifest's recipe into its committed object
(tools/machines/lixr/lixr.o, ld -r of the objects: notes/60 §2), then composes the machine alone through
tools/compose.py, which places that object with tools/relocate.py as any build does. It writes the result into
tweaks/ so that check_overlaps.py, registry.py and build.py -t lixr see it. Needs the m68k toolchain (for the
object); compose.py alone does not.

    python3 tools/gen_lixr.py --cycles model-cycles_OS1.13.syx [--check]
"""
import argparse
import json
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import compose                     # noqa: E402
import gen_macro as gm             # noqa: E402
import gen_sdvintage_exact as gx   # noqa: E402
import gen_sdvintage_7th as g7     # noqa: E402

OUT = compose.DEV / "36-lixr.json"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", required=True, help="official model-cycles_OS1.13.syx")
    ap.add_argument("--check", action="store_true", help="checks that the committed file matches")
    args = ap.parse_args()
    img = g7.cycles_main(args.cycles)
    if len(img) != gx.IMAGE_LEN:
        raise SystemExit("!! not the official MAIN OS 1.13")
    m = compose.load_manifest("lixr")
    with tempfile.TemporaryDirectory() as d:
        obj = compose.build_object(m, pathlib.Path(d))
    bad = compose.emit_bytes(compose.object_path(m), obj, args.check)
    tweak, info = compose.compose(img, ["lixr"])
    tweak["description"].append("Generated by tools/gen_lixr.py through tools/compose.py.")
    text = json.dumps(tweak, indent=1, ensure_ascii=False) + "\n"
    p = info["packages"][0]
    print(f"  lixr: {len(tweak['writes'])} writes, code {p['code']} bytes, variables {p['bss']} bytes, "
          f"{info['image']} bytes added to the image, {len(tweak['conflicts'])} conflicts computed")
    if gm.emit(OUT, text, args.check) or bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
